"""Rebuild the classic-script runtime and deterministic gzip UI assets."""
from pathlib import Path
import gzip

SOURCES=('batch-view.js','media-cards.js','media-cache.js','cloud-ui.js','catalog-ui.js','video-account-ui.js','workspace-shell.js','browser-environment.js','relay-links.js','media-transfer.js','original-file-transfer.js','media-save.js','mobile-performance.js')
def build(root=None):
    root=Path(root) if root else Path(__file__).parent
    static=root/'static'
    chunks=['// Generated by build_web_runtime.py; edit the source modules.\n']
    for name in SOURCES:chunks.append('\n// Source: '+name+'\n'+(static/name).read_text(encoding='utf-8-sig')+'\n;\n')
    chunks.append('\nboot();\n')
    (static/'site-runtime.js').write_text(''.join(chunks),encoding='utf-8')
    for name in ('index.html','workspace.css','site-runtime.js'):
        p=static/name;Path(str(p)+'.gz').write_bytes(gzip.compress(p.read_bytes(),compresslevel=9,mtime=0))
if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser();parser.add_argument('--root');args=parser.parse_args();build(args.root)
